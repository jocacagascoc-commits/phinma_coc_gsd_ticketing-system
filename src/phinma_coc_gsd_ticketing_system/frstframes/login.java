    private void loginbuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginbuttonActionPerformed
    String eM = email.getText().trim().toLowerCase();
    String pW = new String(password.getPassword());
    

    if (eM.isEmpty() || pW.isEmpty())   {
        JOptionPane.showMessageDialog(this, "Please fill in all fields (Email and Password)", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return; //Stop here. Don't continue.
    }
    
    if (!eM.endsWith("@phinmaed.com")) {
            JOptionPane.showMessageDialog(this, "Invalid email format! Please use your official @phinmaed.com email.", "Email Error", JOptionPane.WARNING_MESSAGE);
            return;
        }


    Connection conn = DBConnection.connect();
    
    if (conn == null) {
            JOptionPane.showMessageDialog(this, "Database Connection Error! Please make sure MySQL is running in XAMPP.", "Connection Failed", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String sql = "SELECT * FROM tbl_users WHERE email= ? AND password= ?";

    try {
        PreparedStatement pst = conn.prepareStatement(sql); // ' OR '1'='1 SQL Injection
        pst.setString(1, eM);
        pst.setString(2, pW);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            int userId = rs.getInt("id");
            String dbFullName = rs.getString("full_name");
            String role = rs.getString("role");
            
            UserSession.setUser(userId, eM, dbFullName, role);
            
            String welcomeMessage;
            String dialogTitle;
            
             if ("Admin".equalsIgnoreCase(role)) {
                    welcomeMessage = "Welcome to GSD Admin Portal, " + dbFullName + "!\n" +
                                     "You have full administrative access to manage and resolve tickets.";
                    dialogTitle = "Admin Access Granted";
                    
            } else if ("Student".equalsIgnoreCase(role)) {
                    welcomeMessage = "Welcome back, " + dbFullName + "!\n" +
                                     "You can now submit new service requests and track your tickets.";
                    dialogTitle = "Student Login Successful";

                } else {
                    welcomeMessage = "Welcome back, " + dbFullName + "!";
                    dialogTitle = "Login Successful";
                }

            JOptionPane.showMessageDialog(this, welcomeMessage, dialogTitle, JOptionPane.INFORMATION_MESSAGE);
            
           if ("Admin".equalsIgnoreCase(role)) {
            homepageadmin adminFrame = new homepageadmin();
            adminFrame.setVisible(true);
        } else {
            homepage studentFrame = new homepage();
            studentFrame.setVisible(true);
        }

        this.dispose();
            
        } else {
            JOptionPane.showMessageDialog(this, "Invalid email or password. Please check your credentials and try again.", "Login Failed", JOptionPane.ERROR_MESSAGE);
        }


        conn.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Connection Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
         e.printStackTrace();
        }
    }//GEN-LAST:event_loginbuttonActionPerformed

