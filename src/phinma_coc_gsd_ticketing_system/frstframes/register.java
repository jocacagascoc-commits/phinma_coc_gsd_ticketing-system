    private void loginbuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginbuttonActionPerformed
    String username = txtFullName.getText().trim();
        String password = new String(txtPassword.getPassword());
        String email = txtEmail.getText().trim().toLowerCase();

        // 1. Check for empty fields
        if (username.isEmpty() || password.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Validate PHINMA Email domain
        if (!email.endsWith("@phinmaed.com")) {
            JOptionPane.showMessageDialog(this, "Only official @phinmaed.com emails are allowed.", "Access Denied", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 3. Connect to Database and check for duplicates
        String url = "jdbc:mysql://localhost:3306/phinma_coc_gsd_ticketing_system";
        String dbUser = "root";
        String dbPass = "";

        try (java.sql.Connection conn = java.sql.DriverManager.getConnection(url, dbUser, dbPass)) {
            
            // Check if full_name or email already exists
            String checkSql = "SELECT * FROM tbl_users WHERE full_name = ? OR email = ?";
            try (java.sql.PreparedStatement checkStmt = conn.prepareStatement(checkSql)) {
                checkStmt.setString(1, username);
                checkStmt.setString(2, email);
                java.sql.ResultSet rs = checkStmt.executeQuery();
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "Name or Email is already registered!", "Registration Failed", JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }

            // 4. Generate 6-digit OTP
            String generatedOTP = String.valueOf((int)(Math.random() * 900000) + 100000);

            // 5. Send OTP Email
            JOptionPane.showMessageDialog(this, "Sending OTP to " + email + "... Please wait.", "Sending OTP", JOptionPane.INFORMATION_MESSAGE);
            boolean emailSent = sendOTPEmail(email, generatedOTP);

            if (!emailSent) {
                JOptionPane.showMessageDialog(this, "Failed to send OTP email. Please check your internet connection or email credentials.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 6. Prompt user to enter the OTP
            String userEnteredOTP = JOptionPane.showInputDialog(this, 
                "An OTP has been sent to " + email + ".\nPlease enter the 6-digit code below to complete registration:", 
                "Verify Email OTP", 
                JOptionPane.QUESTION_MESSAGE);

            // 7. Verify OTP
            if (userEnteredOTP == null || !userEnteredOTP.trim().equals(generatedOTP)) {
                JOptionPane.showMessageDialog(this, "Invalid or missing OTP code. Registration cancelled.", "Verification Failed", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 8. OTP Verified -> Insert new user into MySQL
            String insertSql = "INSERT INTO tbl_users (full_name, email, password, role) VALUES (?, ?, ?, ?)";
            try (java.sql.PreparedStatement insertStmt = conn.prepareStatement(insertSql)) {
                insertStmt.setString(1, username);
                insertStmt.setString(2, email);
                insertStmt.setString(3, password);
                insertStmt.setString(4, "Student");

                int rows = insertStmt.executeUpdate();
                if (rows > 0) {
                    JOptionPane.showMessageDialog(this, "Account successfully registered! You can now log in.", "Registration Successful", JOptionPane.INFORMATION_MESSAGE);
                    
                    // Clear inputs after success
                    txtFullName.setText("");
                    txtEmail.setText("");
                    txtPassword.setText("");
                }
            }

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Database Error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }//GEN-LAST:event_loginbuttonActionPerformed

