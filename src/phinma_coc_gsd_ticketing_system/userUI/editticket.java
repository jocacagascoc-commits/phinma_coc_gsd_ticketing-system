    private void submitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitButtonActionPerformed
        String roomLoc = room.getText().trim();
    String bldg = building.getSelectedItem().toString();
    String camp = campus.getSelectedItem().toString();
    String equip = equipment.getSelectedItem().toString();
    String otherEquip = others.getText().trim();
    String prio = priority.getSelectedItem().toString();
    String desc = description.getText().trim();

    if (roomLoc.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid room location.", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    if (desc.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please describe the problem.", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    java.sql.Connection conn = DBConnection.connect();
    if (conn == null) return;

    // Execute UPDATE query for existing ticket
    String sql = "UPDATE tbl_tickets SET room = ?, building = ?, campus = ?, equipment = ?, others_specified = ?, priority = ?, description = ? WHERE ticket_id = ?";

    try (java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
        pstmt.setString(1, roomLoc);
        pstmt.setString(2, bldg);
        pstmt.setString(3, camp);
        pstmt.setString(4, equip);

        if (equip.equalsIgnoreCase("Others")) {
            pstmt.setString(5, otherEquip);
        } else {
            pstmt.setNull(5, java.sql.Types.VARCHAR);
        }
        pstmt.setString(6, prio);
        pstmt.setString(7, desc);
        pstmt.setInt(8, ticketId);

        int rowsUpdated = pstmt.executeUpdate();
        if (rowsUpdated > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ticket updated successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            new status().setVisible(true); // Return to status window
            this.dispose();
        }
    } catch (java.sql.SQLException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error updating ticket: " + ex.getMessage(), "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        ex.printStackTrace();
    } finally {
        try {
            if (conn != null) conn.close();
        } catch (java.sql.SQLException ex) {
            ex.printStackTrace();
        }
    }
    }//GEN-LAST:event_submitButtonActionPerformed

